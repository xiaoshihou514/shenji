"""
dataset.py - memory-mapped dataset loader for sharded NumPy archives.

Each shard is generated by `scripts/preprocess_pgn.py` and contains:
    x : uint8  shape (N, 65)   - board-state tokens
    y : int32  shape (N,)      - target move id
"""
from __future__ import annotations
from pathlib import Path
import numpy as np
import torch
from torch.utils.data import Dataset


class NPZShard(Dataset):
    """Memory-maps a single .npz shard to avoid large RAM spikes."""
    def __init__(self, path: Path):
        self._npz = np.load(path, mmap_mode="r")
        self.x: np.ndarray = self._npz["x"]      # (N, 65) uint8
        self.y: np.ndarray = self._npz["y"]      # (N,)    int32

    def __len__(self) -> int:
        return self.y.shape[0]

    def __getitem__(self, idx: int):
        # Cast once on the fly; avoids an upfront  -->  int64 copy of the shard
        return (
            torch.from_numpy(self.x[idx].astype(np.int64, copy=False)),
            torch.tensor(self.y[idx], dtype=torch.long),
        )


def shard_paths(data_dir: Path, pattern: str) -> list[Path]:
    """Glob shards deterministically so every worker sees the same order."""
    return sorted(data_dir.glob(pattern))


class MultiShard(Dataset):
    """
    Concatenates multiple shards into a single virtual dataset.

    Uses a prefix-sum table (`cum_lens`) to route each global index to the
    correct shard with O(log S) binary search, where S = #shards.
    """
    def __init__(self, data_dir: Path, pattern: str):
        self.shards = [NPZShard(p) for p in shard_paths(data_dir, pattern)]
        lengths = [len(s) for s in self.shards]
        self.cum_lens = np.add.accumulate(lengths)

    def __len__(self) -> int:          # noqa: D401
        return int(self.cum_lens[-1])

    def __getitem__(self, idx: int):
        shard_idx = int(np.searchsorted(self.cum_lens, idx, side="right"))
        inner_idx = idx - (self.cum_lens[shard_idx - 1] if shard_idx else 0)
        return self.shards[shard_idx][inner_idx]
